"""Export the saved model and the station-day features for the interactive demo page
(demo/index.html). The page re-does the model's arithmetic in the browser, so this
file holds exactly what the saved scikit-learn pipeline uses:

    imputer medians -> standard scaling -> logistic regression -> threshold

Run from the project root (after scripts/02_save_model.py):
    python scripts/04_export_demo.py

Writes demo/data.js (embedded data, so the page also works when opened from disk)
and demo/check_probabilities.json (Python's probabilities, used by the test that
proves the page computes the same numbers).
"""
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src import config as C  # noqa: E402
from src.deploy import load_model  # noqa: E402
from src.models import load_choice  # noqa: E402
from src.features import FEATURES, FEATURE_INFO, make_features  # noqa: E402
from src.plots import STATION_ORDER  # noqa: E402

DEMO = C.ROOT / "demo"


def r(v, nd=5):
    return None if (v is None or not np.isfinite(v)) else round(float(v), nd)


def main():
    model, meta = load_model()
    choice = load_choice()
    imp, sc, lr = (model.named_steps["prep"].named_steps["impute"],
                   model.named_steps["prep"].named_steps["scale"], model.named_steps["model"])
    feats = make_features()

    # Same availability rule as the deployed script: a forecast needs day-D weather
    # for the station and at least one station reporting PM2.5 that day.
    has_weather = feats[[c for c in FEATURES if c in ("dewpoint", "rh", "pressure")]].notna().all(axis=1)
    any_pm = feats.groupby("date")["pm25_missing"].transform("min") == 0
    rows = feats[has_weather & any_pm].sort_values(["date", "station"]).reset_index(drop=True)

    p_python = model.predict_proba(rows[FEATURES])[:, 1]
    dates = sorted(rows["date"].dt.strftime("%Y-%m-%d").unique())
    d_index = {d: i for i, d in enumerate(dates)}
    data = {
        "model": {
            "features": FEATURES,
            "labels": {f: FEATURE_INFO[f][1] for f in FEATURES},
            "groups": {f: FEATURE_INFO[f][0] for f in FEATURES},
            "median": [float(v) for v in imp.statistics_],
            "mean": [float(v) for v in sc.mean_],
            "scale": [float(v) for v in sc.scale_],
            "coef": [float(v) for v in lr.coef_[0]],
            "intercept": float(lr.intercept_[0]),
            "threshold": meta["threshold_probability"],
            "rule_ugm3": meta["reference_rule_ugm3"],
            "rule_log": choice["reference"]["threshold_log_pm25"],
            "limit_ugm3": meta["limit_ugm3"],
            "trained_on": meta["trained_on_target_years"],
        },
        "stations": STATION_ORDER,
        "split_years": C.SPLIT_YEARS,
        "festivals": C.FESTIVALS,
        "dates": dates,
        # one row per station-day: [date index, station index, today PM2.5, tomorrow PM2.5, features...]
        "rows": [[d_index[d.strftime("%Y-%m-%d")], STATION_ORDER.index(st),
                  r(np.exp(lp), 2), r(nx, 2), [r(row[f], 12) for f in FEATURES]]
                 for d, st, lp, nx, (_, row) in zip(rows["date"], rows["station"], rows["log_pm25"],
                                                   rows["pm25_next"], rows.iterrows())],
    }
    DEMO.mkdir(exist_ok=True)
    js = "// Generated by scripts/04_export_demo.py. Do not edit by hand.\nwindow.DEMO_DATA = " + \
         json.dumps(data, separators=(",", ":")) + ";\n"
    (DEMO / "data.js").write_text(js, encoding="utf-8", newline="\n")
    (DEMO / "check_probabilities.json").write_text(
        json.dumps([float(p) for p in p_python]) + "\n", encoding="utf-8", newline="\n")
    print(f"demo/data.js: {len(rows)} station-days, {dates[0]} .. {dates[-1]}, "
          f"{(DEMO / 'data.js').stat().st_size / 1e6:.1f} MB")


if __name__ == "__main__":
    main()
